/** Monogram mark used when the shop has no uploaded logo. */
export function Monogram({ name, className }: { name: string; className?: string }) {
  const letter = name.trim().replace(/^(صالون|حلاقة|محل)\s+/, "").charAt(0) || "✂";
  return (
    <span className={`relative grid place-items-center rounded-full border border-gold/50 bg-ink font-display text-gold ${className ?? ""}`}>
      <span className="absolute inset-[3px] rounded-full border border-gold/20" />
      <span className="relative leading-none">{letter}</span>
    </span>
  );
}
